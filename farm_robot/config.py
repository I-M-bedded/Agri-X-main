# 팻말이 고랑 중심선에서 옆으로 치우친 거리(m).
#
# [주의] 이 값은 **시뮬레이터가 팻말을 어디에 세울지**에만 쓰인다.
#   제어 로직은 이 값을 쓰지 않는다.
#   마커는 "여기 고랑 입구가 있다"만 알려주고, 고랑 중심은 비전이
#   직접 찾는다. 팻말 위치를 상수로 알려주는 방식은 현장에서 팻말을
#   조금만 옮겨 박아도 로봇이 이랑으로 돌진하게 만든다.
#   실기에서는 팻말을 고랑이든 이랑이든 편한 곳에 세우면 된다.
#
# ---------------------------------------------------------
# [현장 지침] 그래도 "아무 데나"는 아니다 — 횡오프셋 한계  ★
# ---------------------------------------------------------
#   제어 로직이 이 값을 모른다는 것과, 팻말을 얼마나 치우쳐 박아도
#   되는지는 다른 문제다. 너무 멀리 박으면 로봇이 팻말 앞에 도착했을 때
#   정작 정렬할 고랑이 센서 범위 밖에 있다.
#
#   시뮬레이션으로 한계선을 실측했다 (고랑 3개, 오프셋을 바꿔가며):
#
#     횡오프셋   비전 정상   비전 실명(흐린 날)
#      0.20m      완주         완주
#      0.28m      완주         완주
#      0.31m      완주         완주
#      0.33m      완주        SAFE_HALT (0/3)   <- ToF 탐침 한계
#      0.60m      완주        SAFE_HALT
#      0.65m     SAFE_HALT    SAFE_HALT         <- 비전 한계
#
#   한계가 두 개이고, 각각 근거가 다르다.
#
