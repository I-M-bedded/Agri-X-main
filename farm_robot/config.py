# =========================================================
# 무한궤도(트랙) 차체 파라미터  ★ 반드시 실측
# ---------------------------------------------------------
# 궤도는 바퀴와 물리가 다르다. 두 가지를 꼭 이해하고 값을 넣어야 한다.
#
# (1) 회전할 때 궤도가 지면을 **비비며 미끄러진다** (skid steer)
#     바퀴는 굴러서 돌지만 궤도는 좌우가 반대로 밀면서 지면을 긁는다.
#     그래서 같은 좌우 속도차를 줘도 이론값보다 **덜 돈다**.
#     -> 회전 계산에 쓰는 '유효 궤도 간격'이 실제 간격보다 **넓다**.
#
# (2) 엔코더는 **궤도가 움직인 양**을 재지, 로봇이 간 거리를 재지 않는다
#     궤도가 흙 위에서 헛돌면 그 차이만큼 오차가 난다.
#
# 두 오차 모두 흙 상태에 따라 달라지므로 물리 모델로 예측할 수 없다.
# **실측해서 아래 보정 계수에 넣는 것이 유일한 방법이다.**
# 측정 방법은 tools/setup.py 4번(궤도 보정)을 쓰면 자동으로 안내한다.

# 구동 스프로킷의 유효 반지름(m).
# 궤도가 감기는 바퀴 중심에서 궤도 접지면까지의 거리다.
# (궤도 두께를 포함한 값이므로 스프로킷 반지름보다 조금 크다)
WHEEL_RADIUS_M = 0.033

# 좌우 궤도 접지면 중심 간 **실측** 거리(m). 자로 재면 된다.
TRACK_WIDTH_M = 0.17

# 궤도 미끄러짐 보정 계수. **회전 정밀도를 좌우하는 가장 중요한 값이다.**
#   1.0  = 미끄러짐 없음(바퀴형)
#   1.2~1.5 = 일반적인 궤도 (흙 위)
#   측정: tools/setup.py 4번에서 180도 회전을 시켜 실제 회전각을 잰다.
#         계수 = 명령한 각도 / 실제로 돈 각도
#         예) 180도 명령했는데 140도만 돌았다 -> 180/140 = 1.29
#   너무 작으면 유턴이 모자라고, 너무 크면 지나친다.
TRACK_SLIP_FACTOR = 1.3

# 코드가 회전 계산에 실제로 쓰는 값. 직접 고치지 말고 위 두 값을 조정할 것.
WHEEL_BASE_M = TRACK_WIDTH_M * TRACK_SLIP_FACTOR

# 직진 거리 보정 계수 = (실제 이동 거리) / (엔코더가 추정한 거리)
#   궤도가 헛돌면 엔코더는 더 갔다고 보고한다 -> 1.0 보다 작아진다.
#   측정: tools/setup.py 4번에서 2m 직진시켜 실제 이동 거리를 잰다.
#   딱딱한 바닥이면 1.0 에 가깝고, 무른 흙이면 0.9 근처까지 떨어진다.
DISTANCE_CALIBRATION_FACTOR = 1.0
# 위 ENCODER_EDGE 기준 1회전당 카운트 수.
#   슬롯 20개 인코더 + RISING -> 20
#   슬롯 20개 인코더 + BOTH   -> 40
TICKS_PER_REVOLUTION = 20.0

# 단일 채널 엔코더는 회전 "방향"을 알 수 없으므로, 모터 드라이버가 지시한
# 방향(left_dir/right_dir)을 사용한다. 급감속/미끄러짐 시 오차가 생길 수 있으므로
# 정밀도가 필요하면 쿼드러처(A/B 2채널) 엔코더로 교체할 것.
