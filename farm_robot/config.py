#   좌/우 0.6m 간격이면 이격 0.5~2.0m 전 구간에서 둘 다 화각에 들어온다
#   (최소 베이스라인 GATE_HEADING_ANCHOR_MIN_BASELINE_M=0.4m 도 만족).
#
#   ID 규약: 고랑 k -> 좌 팻말 2k-1, 우 팻말 2k.
#   x 가 커지는 순서와 ID 순서가 일치해야 한다
#   (_reanchor_heading_from_posts 가 'ID 큰 쪽 = 다음 고랑 방향'으로 푼다).
MARKER_PAIR_PER_FURROW = False
MARKER_PAIR_SPACING_M = 0.6      # 좌우 팻말 간격(m)


def furrow_marker_id(furrow_index: int) -> int:
    """furrow_index(1부터) -> 입구 팻말 마커 ID (짝 배치면 우측 팻말)"""
    if MARKER_PAIR_PER_FURROW:
        return 2 * furrow_index
    return furrow_index


def furrow_index_from_marker(marker_id: int) -> int:
    """입구 팻말 마커 ID -> 고랑 번호 (furrow_marker_id 의 역함수)"""
    if MARKER_PAIR_PER_FURROW:
        return (marker_id + 1) // 2
    return marker_id


